/**
 * Ключ превью: ведёт на мини-макет в components/agents/agent-previews.tsx.
 * Ключи совпадают с реестром AGENT_REGISTRY и картой иконок
 * AGENT_CASE_ICONS. Два кейса делят одну визуальную схему (чат, метрики),
 * но контент внутри превью у каждого свой.
 */
export type AgentPreviewKey = 'support' | 'sales' | 'content' | 'analytics' | 'research';

export interface AgentMetric {
  /** Крупное значение: «−68%», «8 сек». */
  value: string;
  /** Подпись под значением. */
  label: string;
}

/** Экран кейса: общий макет CaseMock + описание под ним на странице кейса. */
export interface AgentScreen extends DesignScreen {
  /** Что показывает экран и какую задачу он закрывает. */
  desc: string;
}

export interface AgentCase {
  slug: string;
  title: string;
  /** Одна строка-лид для карточки и шапки страницы кейса. */
  subtitle: string;
  /** Тип агента: поддержка, продажи, контент… */
  agentType: string;
  /** Технологии и интеграции: подписи чипов на странице кейса. */
  stack: string[];
  /** Ровно три метрики: первая попадает в бейдж поверх превью. */
  metrics: AgentMetric[];
  /** Ровно четыре экрана с описаниями. */
  screens: AgentScreen[];
  /** Мини-макет первого экрана для превью карточки. */
  preview: AgentPreviewKey;
  /** Палитра макетов экранов кейса. */
  palette: MockPalette;
}

