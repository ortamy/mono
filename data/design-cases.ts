/**
 * Кейсы портфолио на /design.
 *
 * Отдельный источник данных для сетки и страниц кейсов: главная и
 * [slug] читают один и тот же массив, поэтому описание в карточке и
 * в детальном виде всегда совпадают.
 *
 * Превью — не картинки, а живые макеты: компонент CaseMock рисует SVG
 * по полю screen.kind и палитре кейса (palette). Ассетов нет, поэтому
 * всё резкое на любом DPI и не зависит от темы интерфейса.
 */

export type MockKind =
  | 'landing'
  | 'grid'
  | 'detail'
  | 'dash'
  | 'funnel'
  | 'phone'
  | 'form'
  | 'feed'
  | 'article'
  | 'pricing';

export interface MockPalette {
  bg: string;
  panel: string;
  line: string;
  ink: string;
  muted: string;
  accent: string;
  accentInk: string;
}

export interface DesignMetric {
  /** Крупное значение: «+120%», «14 → 4 мин». */
  value: string;
  /** Подпись под значением. */
  label: string;
}

export interface DesignScreen {
  /** Подпись под макетом. */
  title: string;
  /** Какой экран рисует CaseMock. */
  kind: MockKind;
  /** Логотип в шапке макета. */
  brand?: string;
  /** Крупный заголовок экрана. */
  headline: string;
  /** Подпись под заголовком. */
  sub?: string;
  /** Текст основной кнопки. */
  cta?: string;
  /** Строки: карточки, фильтры, поля, названия. */
  items?: string[];
  /** Значения под items: цены, метрики, статусы. */
  values?: string[];
}

export interface DesignCase {
  slug: string;
  emoji: string;
  title: string;
  /** Категория ниши: E-commerce, Fintech… */
  category: string;
  year: string;
  /** Одна строка для карточки. */
  summary: string;
  /** Живой проект: если есть — карточка и страница ведут на него. */
  url?: string;
  /** Палитра макетов: у каждого кейса своя, как у отдельного скриншота. */
  palette: MockPalette;
  task: string;
  solution: string;
  result: string;
  metrics: DesignMetric[];
  /** Что именно делал дизайнер (чипы на странице кейса). */
  services: string[];
  screens: DesignScreen[];
}

