/**
 * Кейсы портфолио на /design.
 *
 * Единый источник для сетки работ, страниц кейсов и sitemap: карточка и
 * детальный вид читают один массив, поэтому описания не расходятся.
 *
 * Превью кейса — свёрстанный мини-макет первого экрана
 * (components/design/previews/*), экраны проекта на странице кейса рисует
 * CaseMock. Ассетов-скриншотов нет: всё резкое на любом DPI и не зависит
 * от темы интерфейса.
 *
 * Вся палитра — монохром: near-black / near-white и один сдержанный акцент.
 * Проекты — концепты: цифры показывают логику решения, а не подписанный
 * результат клиента.
 */

export type MockKind =
  /* Общие архетипы: лендинг, каталог, форма — подходят любому кейсу. */
  | 'landing'
  | 'grid'
  | 'detail'
  | 'dash'
  | 'funnel'
  | 'phone'
  | 'form'
  | 'feed'
  | 'article'
  | 'pricing'
  /* Отраслевые экраны: рисуют сценарий конкретного продукта. */
  | 'lookbook' // Versta — лукбук и визуальный конструктор модулей
  | 'build' // Versta — сборка конфигурации из блоков
  | 'slots' // Levin — тайм-сетка записи к врачу
  | 'map' // Ukus — карта с маршрутом курьера
  | 'tracker' // Ukus — трекинг заказа и статусы доставки
  | 'receipt' // Ukus — чек и состав заказа
  | 'specsheet' // Ferro — чертёж, миллиметровка, спецификация
  | 'terminal' // Traq — консоль логов, метрики и графики
  | 'apiref' // Base — документация API и код-сэмплы
  | 'ledger' // Nordbank — счета и транзакции
  | 'economics' // Metrik — юнит-экономика, графики, воронка
  | 'chat'; // AI-агенты — диалог пользователя и ассистента

export interface MockPalette {
  bg: string;
  panel: string;
  line: string;
  ink: string;
  muted: string;
  accent: string;
  accentInk: string;
}

/**
 * Какой мини-макет первого экрана рисовать в превью кейса.
 * Ключ ведёт к компоненту в components/design/previews/*.
 */
export type PreviewKey =
  | 'mono'
  | 'lookbook'
  | 'bank'
  | 'dashboard'
  | 'slots'
  | 'map'
  | 'specsheet'
  | 'alephy'
  | 'traq'
  | 'base';

export interface DesignMetric {
  /** Крупное значение: «+120%», «14 → 4 мин». */
  value: string;
  /** Подпись под значением. */
  label: string;
}

export interface DesignScreen {
  /** Подпись под макетом. */
  title: string;
  /** Какой экран рисует CaseMock. */
  kind: MockKind;
  /** Логотип в шапке макета. */
  brand?: string;
  /** Крупный заголовок экрана. */
  headline: string;
  /** Подпись под заголовком. */
  sub?: string;
  /** Текст основной кнопки. */
  cta?: string;
  /** Строки: карточки, фильтры, поля, названия. */
  items?: string[];
  /** Пункты в шапке макета, когда отраслевые подписи по умолчанию не подходят. */
  links?: string[];
  /** Фильтры-чипы каталога или списка: заменяют подписи по умолчанию. */
  filters?: string[];
  /** Блок-сводка формы: заголовок и строки «подпись → значение» справа. */
  summary?: { title: string; items: string[]; values: string[] };
  /** Значения под items: цены, метрики, статусы. */
  values?: string[];
}

export interface DesignCase {
  slug: string;
  title: string;
  /** Категория ниши: E-commerce, Fintech… */
  category: string;
  year: string;
  /** Одна строка для карточки. */
  summary: string;
  /** Живой проект: если есть — карточка и страница ведут на него. */
  url?: string;
  /** Мини-макет первого экрана для превью (см. components/design/previews). */
  preview: PreviewKey;
  /** Палитра макетов: у каждого кейса своя, как у отдельного скриншота. */
  palette: MockPalette;
  task: string;
  solution: string;
  result: string;
  metrics: DesignMetric[];
  /** Что именно делал дизайнер (чипы на странице кейса). */
  services: string[];
  screens: DesignScreen[];
}

